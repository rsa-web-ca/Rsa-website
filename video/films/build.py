"""Generate the page-header films as HyperFrames projects.

Each film is a silent, seamless 12 s loop at 1920x800 in the site palette,
with its motif on the right so page titles sit on calm ground at the left.
Run `python3 build.py`, then in each film folder `npx hyperframes render`.
Loops are seamless because every motion is periodic in the film length:
tracks move exactly one tile, dash offsets one dash period, pulses repeat.
"""

import math
import os
import random
import shutil

W, H, DUR = 1920, 800, 12
HERE = os.path.dirname(os.path.abspath(__file__))
GSAP = os.path.join(HERE, "..", "hero-ledger", "assets", "gsap.min.js")

BASE_CSS = f"""
:root {{
  --ground: #0e1420;
  --rule: rgba(160, 176, 196, 0.2);
  --rule-strong: rgba(160, 176, 196, 0.42);
  --ink: rgba(226, 232, 240, 0.7);
  --muted: rgba(160, 176, 196, 0.45);
  --maroon: #b0213f;
}}
* {{ margin: 0; padding: 0; box-sizing: border-box; }}
html, body {{ width: {W}px; height: {H}px; overflow: hidden; background: var(--ground); }}
#root {{ position: relative; width: 100%; height: 100%; overflow: hidden; background: var(--ground); font-family: "IBM Plex Mono", monospace; }}
.full {{ position: absolute; inset: 0; }}
#shade {{ background: linear-gradient(90deg, var(--ground) 0%, rgba(14,20,32,0.9) 30%, rgba(14,20,32,0.15) 62%, rgba(14,20,32,0) 100%); }}
"""


def page(name, css, body, script):
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <!-- R Shivakumar & Associates — {name} header loop. Generated by video/films/build.py. -->
    <script src="assets/gsap.min.js"></script>
    <style>{BASE_CSS}{css}</style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="scene" class="clip full" data-start="0" data-duration="{DUR}" data-track-index="0" data-layout-allow-overflow data-layout-ignore>
{body}
      </div>
      <div id="shade" class="clip full" data-start="0" data-duration="{DUR}" data-track-index="1" data-layout-ignore></div>
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
{script}
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""


# --- Services: a tax form in perspective, fields ticking off as rows pass ---
def services():
    rows, rh = 14, 72
    out = []
    for copy in range(2):
        for i in range(rows):
            r = random.Random(i * 13 + 5)
            label = r.randint(120, 260)
            boxes = r.choice([0, 6, 8, 10])
            tick = r.random() < 0.45
            cells = "".join("<b></b>" for _ in range(boxes)) if boxes else f'<i style="width:{r.randint(220, 420)}px"></i>'
            out.append(
                f'<div class="row"><span class="n">{i + 1:02d}</span><span class="lab" style="width:{label}px"></span>'
                f'<span class="field">{cells}</span><span class="tk">{"<svg viewBox=\'0 0 24 24\'><path d=\'M4 12.5l5 5L20 6\'/></svg>" if tick else ""}</span></div>'
            )
    css = f"""
#stage {{ perspective: 2400px; perspective-origin: 70% 40%; }}
#sheet {{ position: absolute; left: 760px; top: -120px; width: 1080px; height: 1100px; transform: rotateX(24deg) rotateZ(6deg); transform-origin: 50% 0%;
  -webkit-mask-image: linear-gradient(180deg, transparent, #000 20%, #000 75%, transparent); mask-image: linear-gradient(180deg, transparent, #000 20%, #000 75%, transparent); overflow: hidden;
  border-left: 1px solid var(--rule-strong); }}
.row {{ display: flex; align-items: center; gap: 28px; height: {rh}px; padding: 0 28px; border-bottom: 1px solid var(--rule); }}
.n {{ color: var(--muted); font-size: 18px; width: 34px; }}
.lab {{ height: 6px; border-radius: 3px; background: rgba(160,176,196,0.28); }}
.field {{ display: flex; gap: 6px; flex: 1; }}
.field b {{ width: 34px; height: 38px; border: 1px solid var(--rule-strong); border-radius: 3px; }}
.field i {{ display: block; height: 38px; border: 1px solid var(--rule-strong); border-radius: 3px; }}
.tk svg {{ width: 28px; height: 28px; fill: none; stroke: var(--maroon); stroke-width: 2.4; stroke-linecap: round; stroke-linejoin: round; }}
"""
    body = f'<div id="stage" class="full"><div id="sheet"><div id="track">{"".join(out)}</div></div></div>'
    script = f'tl.fromTo("#track", {{ y: 0 }}, {{ y: -{rows * rh}, duration: {DUR}, ease: "none" }}, 0);'
    return css, body, script


# --- Industries: a sector index, bars breathing on periodic waves ---
def industries():
    n = 38
    bars = []
    for i in range(n):
        maroon = i in (9, 22, 31)
        bars.append(f'<div class="bar{" m" if maroon else ""}" id="b{i}"></div>')
    css = """
#chart { position: absolute; right: 120px; bottom: 150px; width: 1060px; height: 470px; display: flex; align-items: flex-end; gap: 10px;
  -webkit-mask-image: linear-gradient(90deg, transparent, #000 18%); mask-image: linear-gradient(90deg, transparent, #000 18%); }
.bar { flex: 1; height: 100px; background: linear-gradient(180deg, rgba(160,176,196,0.38), rgba(160,176,196,0.08)); border-top: 2px solid rgba(160,176,196,0.6); }
.bar.m { background: linear-gradient(180deg, rgba(176,33,63,0.55), rgba(176,33,63,0.08)); border-top-color: #c8405c; }
#base { position: absolute; right: 120px; bottom: 148px; width: 1060px; height: 1px; background: var(--rule-strong); }
.grid { position: absolute; right: 120px; width: 1060px; height: 1px; background: var(--rule); }
"""
    grid = "".join(f'<div class="grid" style="bottom:{150 + k * 94}px"></div>' for k in range(1, 6))
    body = f'<div class="full">{grid}<div id="chart">{"".join(bars)}</div><div id="base"></div></div>'
    # Heights are a sum of sines whose periods divide the film length, so t=0 and t=DUR match.
    script = f"""
      const bars = Array.from(document.querySelectorAll(".bar"));
      const p = {{ t: 0 }};
      const draw = () => {{
        const a = p.t * Math.PI * 2;
        bars.forEach((b, i) => {{
          const h = 0.42 + 0.22 * Math.sin(a + i * 0.45) + 0.16 * Math.sin(2 * a - i * 0.8) + 0.1 * Math.sin(3 * a + i * 1.7);
          b.style.height = Math.round(470 * Math.max(0.08, Math.min(1, h))) + "px";
        }});
      }};
      tl.fromTo(p, {{ t: 0 }}, {{ t: 1, duration: {DUR}, ease: "none", onUpdate: draw }}, 0);
      draw();
"""
    return css, body, script


# --- About: growth rings, one per year of practice, orbiting dashes ---
def about():
    rings = []
    cx, cy = 1460, 400
    for k in range(29):
        r = 60 + k * 19
        rnd = random.Random(k * 7 + 3)
        dash = rnd.choice([4, 8, 14, 24, 40])
        gap = rnd.choice([6, 10, 18, 30])
        period = dash + gap
        maroon = k == 28
        stroke = "#c8405c" if maroon else f"rgba(160,176,196,{0.14 + 0.012 * (28 - k):.3f})"
        width = 2.2 if maroon else 1.2
        direction = 1 if k % 2 else -1
        # Shift by a whole number of dash periods over the film so the loop closes.
        shift = period * (1 + k % 3) * direction
        rings.append((r, dash, gap, stroke, width, shift))
    circles = "".join(
        f'<circle class="ring" cx="{cx}" cy="{cy}" r="{r}" stroke="{s}" stroke-width="{w}" stroke-dasharray="{d} {g}" data-shift="{sh}" />'
        for r, d, g, s, w, sh in rings
    )
    css = "svg#rings { position: absolute; inset: 0; } .ring { fill: none; }"
    body = f'<svg id="rings" viewBox="0 0 {W} {H}" width="{W}" height="{H}">{circles}</svg>'
    script = f"""
      document.querySelectorAll(".ring").forEach((c) => {{
        const s = parseFloat(c.dataset.shift);
        tl.fromTo(c, {{ attr: {{ "stroke-dashoffset": 0 }} }}, {{ attr: {{ "stroke-dashoffset": s }}, duration: {DUR}, ease: "none" }}, 0);
      }});
"""
    return css, body, script


# --- Careers: an ascending path of steps drifting up and to the left ---
def careers():
    step_w, step_h, steps = 150, 70, 26
    pts = []
    x, y = 0, steps * step_h
    for i in range(steps):
        pts.append(f"{x},{y}")
        x += step_w
        pts.append(f"{x},{y}")
        y -= step_h
    poly = " ".join(pts)
    css = f"""
#path {{ position: absolute; left: 700px; top: -1300px; width: {steps * step_w}px; height: {steps * step_h + 40}px;
  -webkit-mask-image: linear-gradient(90deg, transparent, #000 15%, #000 60%, transparent); mask-image: linear-gradient(90deg, transparent, #000 15%, #000 60%, transparent); }}
#path polyline {{ fill: none; stroke-width: 1.4; }}
"""
    lines = []
    for k, (dx, op) in enumerate([(0, 0.5), (-90, 0.22), (90, 0.22), (-180, 0.12), (180, 0.12)]):
        lines.append(f'<polyline points="{poly}" transform="translate({dx} {-dx * step_h / step_w * 0})" stroke="rgba(160,176,196,{op})" />')
    marks = "".join(
        f'<circle cx="{i * step_w + step_w / 2}" cy="{(steps - i) * step_h}" r="5" fill="#c8405c" />' for i in range(0, steps, 4)
    )
    body = f'<svg id="path" viewBox="0 -20 {steps * step_w} {steps * step_h + 40}"><g id="steps">{"".join(lines)}{marks}</g></svg>'
    # Move exactly 4 steps (the mark spacing) so the frame at DUR equals the frame at 0.
    script = f'tl.fromTo("#path", {{ x: 0, y: 0 }}, {{ x: -{4 * step_w}, y: {4 * step_h}, duration: {DUR}, ease: "none" }}, 0);'
    return css, body, script


# --- Contact: an abstract street grid panning under a fixed office pin ---
def contact():
    tile = 480
    rnd = random.Random(560085)
    roads = []
    for _ in range(9):
        y = rnd.randint(0, tile)
        roads.append(f'<line x1="0" y1="{y}" x2="{tile}" y2="{y}" stroke-width="{rnd.choice([1, 1, 2])}" />')
    for _ in range(9):
        x = rnd.randint(0, tile)
        roads.append(f'<line x1="{x}" y1="0" x2="{x}" y2="{tile}" stroke-width="{rnd.choice([1, 1, 2])}" />')
    roads.append(f'<line x1="0" y1="{tile * 0.7}" x2="{tile}" y2="{tile * 0.3}" stroke-width="3" />')
    css = f"""
#map {{ position: absolute; left: 0; top: 0; width: {W + tile * 2}px; height: {H + tile * 2}px;
  -webkit-mask-image: radial-gradient(60% 90% at 72% 50%, #000 30%, transparent 75%); mask-image: radial-gradient(60% 90% at 72% 50%, #000 30%, transparent 75%); }}
#pin {{ position: absolute; left: 1380px; top: 400px; }}
#pin .dot {{ position: absolute; left: -9px; top: -9px; width: 18px; height: 18px; border-radius: 50%; background: #c8405c; box-shadow: 0 0 0 4px rgba(200,64,92,0.25); }}
#pin .wave {{ position: absolute; left: -90px; top: -90px; width: 180px; height: 180px; border-radius: 50%; border: 2px solid rgba(200,64,92,0.6); }}
"""
    body = f"""<div id="mapwrap" class="full"><svg id="map" viewBox="0 0 {W + tile * 2} {H + tile * 2}">
  <defs><pattern id="streets" width="{tile}" height="{tile}" patternUnits="userSpaceOnUse"><g stroke="rgba(160,176,196,0.22)">{''.join(roads)}</g></pattern></defs>
  <rect width="100%" height="100%" fill="url(#streets)" /></svg></div>
<div id="pin"><div class="wave" id="w1"></div><div class="wave" id="w2"></div><div class="dot"></div></div>"""
    script = f"""
      tl.fromTo("#map", {{ x: 0, y: 0 }}, {{ x: -{tile}, y: -{tile // 2 * 0}, duration: {DUR}, ease: "none" }}, 0);
      // Pulses repeat every 3 s (4 per loop); the second ring is offset by half a pulse and rests
      // invisible at both ends of the film, so frame 0 and frame 12 s match.
      tl.set("#w2", {{ opacity: 0 }}, 0);
      for (let k = 0; k < 4; k++) {{
        tl.fromTo("#w1", {{ scale: 0.1, opacity: 0.9 }}, {{ scale: 1, opacity: 0, duration: 3, ease: "power2.out", immediateRender: false }}, k * 3);
      }}
      for (let k = 0; k < 3; k++) {{
        tl.fromTo("#w2", {{ scale: 0.1, opacity: 0.9 }}, {{ scale: 1, opacity: 0, duration: 3, ease: "power2.out", immediateRender: false }}, k * 3 + 1.5);
      }}
"""
    return css, body, script


# --- Compliance: a month grid in perspective, a review highlight stepping through due dates ---
def compliance():
    cells = []
    due = {7: "TDS", 11: "R1", 13: "IFF", 15: "PF", 20: "3B", 22: "QR", 25: "PMT", 30: "ITR"}
    for d in range(1, 36):
        day = d if d <= 31 else ""
        mark = due.get(d)
        cells.append(
            f'<div class="cell{" due" if mark else ""}" id="c{d}"><span>{day}</span>{f"<em>{mark}</em>" if mark else ""}</div>'
        )
    css = """
#stage { perspective: 2200px; perspective-origin: 72% 40%; }
#cal { position: absolute; left: 860px; top: 70px; width: 980px; display: grid; grid-template-columns: repeat(7, 1fr); gap: 10px;
  transform: rotateX(28deg) rotateZ(-6deg); transform-origin: 50% 0%;
  -webkit-mask-image: linear-gradient(180deg, #000 60%, transparent); mask-image: linear-gradient(180deg, #000 60%, transparent); }
.cell { position: relative; height: 112px; border: 1px solid var(--rule-strong); border-radius: 6px; padding: 12px 14px; color: var(--muted); font-size: 20px; }
.cell em { position: absolute; left: 14px; bottom: 12px; font-style: normal; font-size: 15px; color: rgba(226,232,240,0.75); letter-spacing: 0.04em; }
.cell.due::after { content: ""; position: absolute; right: 12px; top: 14px; width: 9px; height: 9px; border-radius: 50%; background: #c8405c; }
#hl { position: absolute; left: 0; top: 0; width: 130px; height: 112px; border: 2px solid #c8405c; border-radius: 6px; background: rgba(176,33,63,0.16); }
"""
    body = f'<div id="stage" class="full"><div id="cal">{"".join(cells)}<div id="hl"></div></div></div>'
    order = [7, 11, 13, 15, 20, 22, 25, 30]
    step = DUR / len(order)
    script = f"""
      const order = {order};
      const cal = document.getElementById("cal");
      const pos = (d) => {{ const el = document.getElementById("c" + d); return {{ x: el.offsetLeft, y: el.offsetTop, w: el.offsetWidth }}; }};
      const first = pos(order[0]);
      gsap.set("#hl", {{ width: first.w }});
      tl.set("#hl", {{ x: first.x, y: first.y }}, 0);
      order.forEach((d, i) => {{
        const next = pos(order[(i + 1) % order.length]);
        tl.to("#hl", {{ x: next.x, y: next.y, duration: 0.6, ease: "power3.inOut" }}, (i + 1) * {step:.3f} - 0.6);
      }});
"""
    return css, body, script


